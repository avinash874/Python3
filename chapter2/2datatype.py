#  Data type batata hai ki variable kis type ka data store kar raha hai.
# Variables
name = "Avinash" # String data type
age = 21 # Integer data type
cgpa = 8.5 # Float data type
is_student = True  # Boolean data type

# Printing values
print(name)
print(age)
print(cgpa)
print(is_student)

# Printing data types
print(type(name))
