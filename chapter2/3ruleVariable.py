# Rules for Naming Variables in Python
# ✅ 1. Variable name must start with a letter (A-Z, a-z) or underscore (_)
# ✅ 2. After the first character, letters, numbers, and underscores are allowed
# ❌ 3. Spaces are not allowed
# ❌ 4. Special characters are not allowed
# ❌ 5. Python keywords cannot be used as variable names
# ✅ 6. Variable names are case-sensitive