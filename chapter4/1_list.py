# List is a collection of items in a particular order. It is mutable and can contain duplicate elements. Lists are defined using square brackets [].
# Unlike strings, lists are mutable, which means we can change their content without changing their identity. We can add, remove, or modify elements in a list after it has been created.

friends = ["apple", "Orange" , 5, 355.06, "false", "Avinash", "Rahul"]
print(friends[0])
print(friends[4])
print(friends[5])

friends[0] = "Mango"
print(friends[0])